#!/usr/bin/env node
/**
 * One-time move of StudentTracker's Firestore data into the trainings tables.
 * Runs on your machine; nothing is uploaded anywhere by this script except the
 * reads from your own Firestore project.
 *
 *   1. node scripts/firestore-import.mjs export <firebase-project-id> <web-api-key> > firestore.json
 *      (the collections are public-read in the old rules, so the web API key is enough)
 *   2. node scripts/firestore-import.mjs mapping firestore.json > mapping.csv
 *      Fill the "email" column with each person's NeatSystem (Google) email.
 *      Rows left empty are skipped — import them later once that person has joined NeatSystem.
 *   3. node scripts/firestore-import.mjs sql firestore.json mapping.csv > import.sql
 *      Read it, then run it in the Supabase SQL editor (after the migrations).
 *      Re-runnable: it upserts.
 */
import { readFileSync } from 'node:fs'

const [cmd, a, b] = process.argv.slice(2)
const COLLECTIONS = ['people', 'teams', 'meta', 'events', 'leads', 'mentors']

// ---------------------------------------------------------------- export
function val(v) {
  if (!v) return null
  if ('stringValue' in v) return v.stringValue
  if ('integerValue' in v) return Number(v.integerValue)
  if ('doubleValue' in v) return v.doubleValue
  if ('booleanValue' in v) return v.booleanValue
  if ('timestampValue' in v) return v.timestampValue
  if ('nullValue' in v) return null
  if ('arrayValue' in v) return (v.arrayValue.values ?? []).map(val)
  if ('mapValue' in v) return Object.fromEntries(Object.entries(v.mapValue.fields ?? {}).map(([k, x]) => [k, val(x)]))
  return null
}
async function exportAll(project, key) {
  const out = {}
  for (const c of COLLECTIONS) {
    out[c] = []
    let token = ''
    do {
      const u = `https://firestore.googleapis.com/v1/projects/${project}/databases/(default)/documents/${c}?pageSize=300&key=${key}${token ? `&pageToken=${token}` : ''}`
      const r = await fetch(u)
      if (!r.ok) { console.error(`${c}: ${r.status} ${await r.text()}`); break }
      const j = await r.json()
      for (const d of j.documents ?? []) out[c].push({ id: d.name.split('/').pop(), ...val({ mapValue: { fields: d.fields ?? {} } }) })
      token = j.nextPageToken ?? ''
    } while (token)
  }
  return out
}

// ---------------------------------------------------------------- sql
const q = (s) => (s == null ? 'null' : `'${String(s).replace(/'/g, "''")}'`)
const slug = (s) => String(s).toLowerCase().replace(/[^a-z0-9_]/g, '_').replace(/^[^a-z]+/, 'x') || 'x'
const TEAM_IDS = new Set(['build', 'cad', 'software'])
const EVENT = { tool_granted: 'granted', tool_revoked: 'revoked', teach_granted: 'teach_granted', teach_revoked: 'teach_revoked', note: 'note', promoted: 'rank_set', rank_set: 'rank_set', rank_auto: 'rank_auto', team_joined: 'joined', team_deactivated: 'deactivated', team_reactivated: 'reactivated' }

function toSql(fs, mapping) {
  const out = ['-- generated by scripts/firestore-import.mjs — review before running', 'begin;',
    'create temp table fs_map (fs_id text primary key, email text) on commit drop;']
  for (const [id, email] of mapping) out.push(`insert into fs_map values (${q(id)}, lower(${q(email)}));`)
  out.push(`create temp view fs_user as select m.fs_id, p.id as uid from fs_map m join hub.profiles p on lower(p.email) = m.email;`)
  const catOf = new Map()
  for (const t of fs.teams) {
    const cid = slug(t.id)
    catOf.set(t.id, cid)
    const cols = (t.order ?? Object.keys(t.categories ?? {})).filter((k) => t.categories?.[k]).map((k) => ({ id: slug(k), he: t.categories[k].he ?? k, label: t.categories[k].label ?? t.categories[k].he ?? k, header: t.categories[k].header ?? '#6D6D6D' }))
    const team = TEAM_IDS.has(cid) ? cid : null
    out.push(`insert into trainings.categories (id, name, kind, team, sort, item_noun, item_noun_singular, favorite_label, columns) values (${q(cid)}, ${q(t.name ?? cid)}, ${q(team ? 'team' : 'special')}, ${q(team)}, ${Number(t.sort ?? 50)}, ${q(t.itemNoun ?? 'הכשרות')}, ${q(t.itemNounSingular ?? 'הכשרה')}, ${q(t.favoriteLabel ?? 'דבר אהוב')}, ${q(JSON.stringify(cols.length ? cols : [{ id: 's0', he: 'שלב א׳', label: 'שלב א׳', header: '#6D6D6D' }]))}::jsonb)
  on conflict (id) do update set name = excluded.name, columns = excluded.columns, item_noun = excluded.item_noun, item_noun_singular = excluded.item_noun_singular, favorite_label = excluded.favorite_label;`)
    let n = 0
    for (const k of t.order ?? Object.keys(t.categories ?? {})) for (const name of t.categories?.[k]?.items ?? []) {
      out.push(`insert into trainings.items (id, category, name, column_id, sort) values (trainings.item_id(${q(cid)}, ${q(name)}), ${q(cid)}, ${q(name)}, ${q(slug(k))}, ${n++}) on conflict (id) do update set column_id = excluded.column_id, sort = excluded.sort;`)
    }
    for (const [rank, req] of Object.entries(t.requirements ?? {})) {
      const items = (req.items ?? []).map((x) => `trainings.item_id(${q(cid)}, ${q(x)})`).join(', ')
      out.push(`insert into trainings.rank_rules (category, rank, items, min_grade) select ${q(cid)}, ${q(rank)}, array[${items}]::text[], ${req.minGrade ?? 'null'} where exists (select 1 from trainings.ranks where id = ${q(rank)})
  on conflict (category, rank) do update set items = excluded.items, min_grade = excluded.min_grade;`)
    }
  }
  for (const p of fs.people) {
    for (const [team, m] of Object.entries(p.memberships ?? {})) {
      const cid = catOf.get(team) ?? slug(team)
      for (const [name, r] of Object.entries(m.items ?? {})) {
        out.push(`insert into trainings.certs (user_id, item, at, teach, teach_at) select u.uid, trainings.item_id(${q(cid)}, ${q(name)}), coalesce(${q(r?.at)}::timestamptz, now()), ${!!r?.canTeach}, ${q(r?.teachAt)}::timestamptz from fs_user u where u.fs_id = ${q(p.id)} and exists (select 1 from trainings.items i where i.id = trainings.item_id(${q(cid)}, ${q(name)})) on conflict do nothing;`)
      }
      if (m.rankId) out.push(`insert into trainings.rank_current (user_id, category, rank, manual) select u.uid, ${q(cid)}, ${q(m.rankId)}, ${m.autoRank === false} from fs_user u where u.fs_id = ${q(p.id)} on conflict (user_id, category) do update set rank = excluded.rank, manual = excluded.manual;`)
      if (m.favorite) out.push(`insert into trainings.favorites select u.uid, ${q(cid)}, left(${q(m.favorite)}, 40) from fs_user u where u.fs_id = ${q(p.id)} on conflict (user_id, category) do update set text = excluded.text;`)
      if (m.active === false) out.push(`insert into trainings.memberships (user_id, category, kind, active) select u.uid, ${q(cid)}, 'paused', false from fs_user u where u.fs_id = ${q(p.id)} on conflict do nothing;`)
    }
  }
  for (const e of fs.events) {
    const type = EVENT[e.type]
    if (!type || !e.personId) continue
    const cid = catOf.get(e.teamId) ?? (e.teamId ? slug(e.teamId) : null)
    const item = e.tool && cid ? `trainings.item_id(${q(cid)}, ${q(e.tool)})` : 'null'
    out.push(`insert into trainings.events (at, type, user_id, category, item, text) select coalesce(${q(e.at)}::timestamptz, now()), ${q(type)}, u.uid, ${q(cid)}, ${type.startsWith('rank') ? q(e.to) : item}, ${q(type === 'note' ? e.text : null)} from fs_user u where u.fs_id = ${q(e.personId)};`)
  }
  for (const l of fs.leads) if (l.canEdit === false) out.push(`-- lead ${q(l.name)} was locked in StudentTracker: lock them in NeatSystem → הכשרות → ניהול → מאשרים (by person), since leads map by Google uid, not by this export.`)
  out.push('commit;')
  return out.join('\n')
}

// ---------------------------------------------------------------- main
if (cmd === 'export') {
  if (!a || !b) { console.error('usage: export <project-id> <web-api-key>'); process.exit(1) }
  console.log(JSON.stringify(await exportAll(a, b), null, 1))
} else if (cmd === 'mapping') {
  const fs = JSON.parse(readFileSync(a, 'utf8'))
  console.log('firestore_id,name,email')
  for (const p of fs.people) console.log(`${p.id},"${String(p.name ?? '').replace(/"/g, '""')}",`)
} else if (cmd === 'sql') {
  const fs = JSON.parse(readFileSync(a, 'utf8'))
  const rows = readFileSync(b, 'utf8').trim().split('\n').slice(1).map((l) => { const id = l.split(',')[0]; const email = l.split(',').pop().trim(); return [id, email] }).filter(([, e]) => e)
  console.log(toSql(fs, rows))
} else {
  console.error('commands: export | mapping | sql   (see the comment at the top)')
  process.exit(1)
}
